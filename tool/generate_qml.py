#!/usr/bin/env python3
"""Generate the QML rendition of Meridian's tokens from the same sources as the
Flutter and web tokens.

Reads tokens/meridian.tokens.json, tokens/brands/*.json, tokens/icons.json with
assets/icons/*.svg, and the layout constants in
lib/src/foundation/meridian_layout.dart. Writes the generated files of the
`Meridian` QML module under qml/Meridian/:

  Tokens.qml        singleton: palettes per brand and theme, brands, spacing,
                    sizes, radii, shadows, motion durations, curves, springs
  ColorScheme.qml   typed colour roles resolved from one palette
  TypeScale.qml     typed fonts and line heights for desktop and touch
  Metrics.qml       singleton: MeridianLayout and MeridianOpacity constants
  IconData.qml      singleton: Lucide outlines as SVG path data
  fonts/            the fonts the package bundles (JetBrains Mono)

  python3 tool/generate_qml.py           write the files
  python3 tool/generate_qml.py --check   write nothing; fail when one is stale

`tool/generate.py` runs this generator too, so one command keeps every
rendition in step. This script needs no Dart toolchain.
"""
from __future__ import annotations

import json
import math
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import generate as core_gen  # noqa: E402  (shared loader, palette and contrast floors)

ROOT = core_gen.ROOT
QML_DIR = ROOT / "qml" / "Meridian"
LAYOUT_DART = ROOT / "lib" / "src" / "foundation" / "meridian_layout.dart"
ICONS_JSON = ROOT / "tokens" / "icons.json"
ICON_DIR = ROOT / "assets" / "icons"
FONT_DIR = ROOT / "assets" / "fonts"

HEADER = ("// GENERATED by tool/generate_qml.py from tokens/, assets/icons/ and "
          "meridian_layout.dart. Do not edit.\n")
LAYOUT_CLASSES = ("MeridianLayout", "MeridianOpacity")


def camel(name: str) -> str:
    return core_gen.camel(name)


def qml_color(value: str) -> str:
    r, g, b, a = core_gen.parse_color(value)
    if a >= 1:
        return f"#{r:02x}{g:02x}{b:02x}"
    return f"#{round(a * 255):02x}{r:02x}{g:02x}{b:02x}"


def num(x: float) -> str:
    s = f"{x:.6f}".rstrip("0").rstrip(".")
    return s or "0"


def js(value) -> str:
    """Compact JSON that QML parses as a JavaScript literal."""
    return json.dumps(value, ensure_ascii=False, separators=(", ", ": "))


# ---------------------------------------------------------------- shadows

def parse_shadow(css: str) -> list[dict]:
    layers = []
    for part in re.split(r",(?![^()]*\))", css):
        tokens = part.strip().split()
        color = next(t for t in tokens if t.startswith(("rgba", "rgb", "#")))
        lengths = [core_gen.px(t) for t in tokens if t is not color and not t.startswith(("rgba", "rgb", "#"))]
        while len(lengths) < 4:
            lengths.append(0.0)
        x, y, blur, spread = lengths[:4]
        layers.append({"x": x, "y": y, "blur": blur, "spread": spread, "color": qml_color(color)})
    return layers


# ---------------------------------------------------------------- springs

SPRING_SEGMENTS = 10


def spring_position(stiffness: float, ratio: float, t: float) -> tuple[float, float]:
    """Position and velocity of a unit spring (mass 1) released from 0 towards 1."""
    omega = math.sqrt(stiffness)
    zeta = ratio
    if zeta < 1:
        wd = omega * math.sqrt(1 - zeta * zeta)
        e = math.exp(-zeta * omega * t)
        x = 1 - e * (math.cos(wd * t) + (zeta * omega / wd) * math.sin(wd * t))
        v = e * (omega * omega / wd) * math.sin(wd * t)
    else:
        e = math.exp(-omega * t)
        x = 1 - e * (1 + omega * t)
        v = e * omega * omega * t
    return x, v


def spring_spline(stiffness: float, ratio: float) -> tuple[int, list[float]]:
    """A spring as a QML Easing.BezierSpline over its settle time.

    The settle time is the same as the web rendition's (core_gen.spring_samples:
    within 0.1% of rest). The path is fitted with SPRING_SEGMENTS cubic Hermite
    segments from the analytic position and velocity. Keep the segment count
    small: Qt 6.11/6.12 corrupts its heap with very long spline lists."""
    duration = (len(core_gen.spring_samples(stiffness, ratio)) - 1) * 8
    total = duration / 1000
    curve: list[float] = []
    n = SPRING_SEGMENTS
    for i in range(n):
        u0, u1 = i / n, (i + 1) / n
        x0, v0 = spring_position(stiffness, ratio, u0 * total)
        x1, v1 = spring_position(stiffness, ratio, u1 * total)
        if i == n - 1:
            x1, v1 = 1.0, 0.0
        h = u1 - u0
        m0, m1 = v0 * total, v1 * total  # dy/du in normalised time
        curve += [u0 + h / 3, x0 + m0 * h / 3, u1 - h / 3, x1 - m1 * h / 3, u1, x1]
    return duration, [float(num(v)) for v in curve]


# ---------------------------------------------------------------- Tokens.qml

def gen_tokens(core, brands) -> str:
    palettes = {}
    brand_meta = {}
    for b in brands:
        palettes[b["id"]] = {
            theme: {camel(k): qml_color(v) for k, v in core_gen.palette(core, b, theme).items()}
            for theme in ("light", "dark")
        }
        fonts = b.get("fonts") or {}

        def family(key):
            f = fonts.get(key) or {}
            return f.get("flutter") or ""

        brand_meta[b["id"]] = {
            "id": b["id"],
            "name": b["name"],
            "density": b.get("density", "regular"),
            "sans": family("sans"),
            "mono": family("mono") or "JetBrains Mono",
            "reading": family("reading"),
            "radius": {camel(k.replace("radius-", "")): core_gen.px(v) for k, v in (b.get("radius") or {}).items()},
        }
    radius = {camel(t["name"].replace("radius-", "")): core_gen.px(t["value"]) for t in core["radius"]["tokens"]}
    space = {camel(t["name"]): core_gen.px(t["value"]) for t in core["spacing"]["tokens"]}
    size = {camel(t["name"].replace("size-", "")): core_gen.px(t["value"]) for t in core["size"]["tokens"]}
    shadows = {
        theme: {camel(t["name"].replace("shadow-", "")): parse_shadow(t["value"][theme]) for t in core["shadow"]["tokens"]}
        for theme in ("light", "dark")
    }
    motion = core["motion"]
    durations = {camel(t["name"].replace("motion-", "")): int(t["value"]) for t in motion["tokens"]}
    curves = {camel(c["name"]): list(c["cubic"]) + [1, 1] for c in motion["curves"]}
    springs = {}
    for sp in motion["springs"]:
        duration, curve = spring_spline(sp["stiffness"], sp["ratio"])
        springs[camel(sp["name"])] = {"duration": duration, "curve": curve}
    scales = {camel(s["name"]): s["value"] for s in motion["scales"]}

    out = [HEADER, "pragma Singleton\nimport QtQuick\n\n", "QtObject {\n"]
    out.append(f"    readonly property string version: {js(str(core['version']))}\n")
    out.append(f"    readonly property var brandIds: {js([b['id'] for b in brands])}\n")
    out.append(f"    readonly property var brands: ({js(brand_meta)})\n")
    out.append(f"    readonly property var palettes: ({js(palettes)})\n")
    out.append(f"    readonly property var radius: ({js(radius)})\n")
    out.append(f"    readonly property var space: ({js(space)})\n")
    out.append(f"    readonly property var size: ({js(size)})\n")
    out.append(f"    readonly property var shadows: ({js(shadows)})\n")
    out.append(f"    readonly property var durations: ({js(durations)})\n")
    out.append(f"    readonly property var curves: ({js(curves)})\n")
    out.append(f"    readonly property var springs: ({js(springs)})\n")
    out.append(f"    readonly property var scales: ({js(scales)})\n")
    out.append("}\n")
    return "".join(out)


# ---------------------------------------------------------------- ColorScheme.qml

def gen_color_scheme(core) -> str:
    names = [t["name"] for t in core["color"]["tokens"]] + [t["name"] for t in core["accent"]["tokens"]] \
        + [t["name"] for t in core["syntax"]["tokens"]]
    usage = {t["name"]: t["usage"] for key in ("color", "accent", "syntax") for t in core[key]["tokens"]}
    out = [HEADER, "import QtQuick\n\n",
           "// The colour roles of one brand in one theme. Theme owns the instance\n",
           "// apps read (Theme.colors); set `palette` to an entry of Tokens.palettes.\n",
           "QtObject {\n", "    property var palette: ({})\n\n"]
    for n in names:
        first = re.split(r"(?<=\.)\s", usage[n].strip())[0]
        out.append(f"    /// {first}\n")
        out.append(f"    readonly property color {camel(n)}: palette.{camel(n)} ?? \"transparent\"\n")
    out.append("}\n")
    return "".join(out)


# ---------------------------------------------------------------- TypeScale.qml

def gen_type_scale(core) -> str:
    groups = {g["name"]: g for g in core["type"]["groups"]}
    desktop = groups["Desktop"]["styles"]
    touch = {s["name"].removesuffix("-touch"): s for s in groups["Touch"]["styles"]}
    out = [HEADER, "import QtQuick\n\n",
           "// Meridian's type scale. Theme sets `touch` from the density and the\n",
           "// families from the brand; read styles as Theme.type.body and\n",
           "// Theme.type.bodyLineHeight.\n",
           "QtObject {\n",
           "    property bool touch: false\n",
           "    /// The platform's text scale (GTK's text-scaling-factor on Linux).\n",
           "    property real scale: 1\n",
           "    property string sansFamily: \"\"\n",
           "    property string monoFamily: \"JetBrains Mono\"\n",
           "    property string readingFamily: \"\"\n",
           "    readonly property string _systemFamily: Application.font.family\n\n"]
    fam_expr = {
        "sans": "(sansFamily.length > 0 ? sansFamily : _systemFamily)",
        "mono": "monoFamily",
        "reading": "(readingFamily.length > 0 ? readingFamily : (sansFamily.length > 0 ? sansFamily : _systemFamily))",
    }
    for s in desktop:
        base = s["name"]
        t = touch.get(base, s)
        name = camel(base)
        family = fam_expr[s.get("family", "sans")]

        def spacing(style):
            ls = style.get("letterSpacing")
            if not ls:
                return 0.0
            return float(ls.replace("em", "")) * core_gen.px(style["fontSize"])

        ds, ts = core_gen.px(s["fontSize"]), core_gen.px(t["fontSize"])
        dl, tl = core_gen.px(s["lineHeight"]), core_gen.px(t["lineHeight"])
        first = re.split(r"(?<=\.)\s", s["usage"].strip())[0]
        out.append(f"    /// {first}\n")
        out.append(
            f"    readonly property font {name}: Qt.font({{ family: {family}, "
            f"pixelSize: Math.round((touch ? {num(ts)} : {num(ds)}) * scale), weight: touch ? {t['fontWeight']} : {s['fontWeight']}, "
            f"letterSpacing: (touch ? {num(spacing(t))} : {num(spacing(s))}) * scale"
            + (", capitalization: Font.AllUppercase" if base == "overline" else "") + " })\n")
        out.append(f"    readonly property real {name}LineHeight: Math.round((touch ? {num(tl)} : {num(dl)}) * scale)\n")
    out.append("}\n")
    return "".join(out)


# ---------------------------------------------------------------- Metrics.qml

CONST_RE = re.compile(r"^\s*static const (double|int|Duration) (\w+)\s*=\s*(.+?);\s*$")


def token_namespaces() -> dict[str, object]:
    """The generated Dart token classes that layout constants may reference."""
    from types import SimpleNamespace
    core = json.loads(core_gen.CORE.read_text())
    motion = core["motion"]
    return {
        "MeridianMotionScales": SimpleNamespace(**{camel(s["name"]): float(s["value"]) for s in motion["scales"]}),
        "MeridianSpace": SimpleNamespace(**{camel(t["name"]): core_gen.px(t["value"]) for t in core["spacing"]["tokens"]}),
        "MeridianSize": SimpleNamespace(**{camel(t["name"].replace("size-", "")): core_gen.px(t["value"]) for t in core["size"]["tokens"]}),
    }


def parse_layout() -> dict[str, dict[str, float]]:
    """Static constants of the layout classes. Fails on any constant this parser
    cannot evaluate, so the QML rendition cannot silently drift."""
    text = LAYOUT_DART.read_text()
    namespaces = token_namespaces()
    classes: dict[str, dict[str, float]] = {}
    current = None
    depth = 0
    for line in text.splitlines():
        m = re.match(r"^abstract final class (\w+)", line)
        if m and depth == 0:
            current = m.group(1)
            classes.setdefault(current, {})
        if current and depth >= 1:
            c = CONST_RE.match(line)
            if c:
                kind, name, expr = c.groups()
                values = classes[current]
                if kind == "Duration":
                    d = re.fullmatch(r"Duration\(milliseconds:\s*(\d+)\)", expr)
                    if not d:
                        raise SystemExit(f"meridian_layout.dart: cannot read Duration {current}.{name} = {expr}")
                    values[name] = float(d.group(1))
                else:
                    env = {**namespaces, **values}
                    if not re.fullmatch(r"[\w\s.+\-*/()]+", expr):
                        raise SystemExit(f"meridian_layout.dart: cannot read {current}.{name} = {expr}")
                    try:
                        values[name] = float(eval(expr, {"__builtins__": {}}, env))  # noqa: S307 (validated arithmetic)
                    except Exception as exc:  # pragma: no cover - reports the constant
                        raise SystemExit(f"meridian_layout.dart: cannot evaluate {current}.{name} = {expr}: {exc}")
            elif re.match(r"^\s*static const ", line):
                raise SystemExit(f"meridian_layout.dart: unsupported constant: {line.strip()}")
        depth += line.count("{") - line.count("}")
        if depth == 0:
            current = None
    return {k: v for k, v in classes.items() if k in LAYOUT_CLASSES}


def gen_metrics() -> str:
    classes = parse_layout()
    out = [HEADER, "pragma Singleton\nimport QtQuick\n\n",
           "// MeridianLayout (component geometry) and MeridianOpacity, as the Flutter\n",
           "// library defines them. Opacity constants carry the `opacity` prefix.\n",
           "QtObject {\n"]
    for name, value in classes["MeridianLayout"].items():
        out.append(f"    readonly property real {name}: {num(value)}\n")
    for name, value in classes["MeridianOpacity"].items():
        out.append(f"    readonly property real opacity{name[:1].upper()}{name[1:]}: {num(value)}\n")
    out.append("}\n")
    return "".join(out)


# ---------------------------------------------------------------- IconData.qml

def _f(v: str | None) -> float:
    return float(v) if v is not None else 0.0


def element_path(el: ET.Element) -> str:
    tag = el.tag.split("}")[-1]
    a = el.attrib
    if tag == "path":
        d = a["d"].strip()
        # A path's first moveto is absolute even when written `m` (its
        # implicit pairs stay relative linetos). Joined to the previous
        # element it would start from that element's end, so reset the
        # current point to the origin first.
        return "M0 0" + d if d.startswith("m") else d
    if tag == "circle":
        cx, cy, r = _f(a.get("cx")), _f(a.get("cy")), _f(a.get("r"))
        return (f"M{num(cx - r)} {num(cy)}a{num(r)} {num(r)} 0 1 0 {num(2 * r)} 0"
                f"a{num(r)} {num(r)} 0 1 0 {num(-2 * r)} 0")
    if tag == "line":
        return f"M{num(_f(a.get('x1')))} {num(_f(a.get('y1')))}L{num(_f(a.get('x2')))} {num(_f(a.get('y2')))}"
    if tag == "polyline":
        pts = re.split(r"[\s,]+", a["points"].strip())
        pairs = [f"{pts[i]} {pts[i + 1]}" for i in range(0, len(pts), 2)]
        return "M" + "L".join(pairs)
    if tag == "rect":
        x, y, w, h = _f(a.get("x")), _f(a.get("y")), _f(a.get("width")), _f(a.get("height"))
        rx = a.get("rx")
        ry = a.get("ry", rx)
        rx_v, ry_v = _f(rx), _f(ry)
        if rx_v <= 0:
            return f"M{num(x)} {num(y)}h{num(w)}v{num(h)}h{num(-w)}Z"
        rx_v, ry_v = min(rx_v, w / 2), min(ry_v, h / 2)
        return (f"M{num(x + rx_v)} {num(y)}h{num(w - 2 * rx_v)}"
                f"a{num(rx_v)} {num(ry_v)} 0 0 1 {num(rx_v)} {num(ry_v)}v{num(h - 2 * ry_v)}"
                f"a{num(rx_v)} {num(ry_v)} 0 0 1 {num(-rx_v)} {num(ry_v)}h{num(-(w - 2 * rx_v))}"
                f"a{num(rx_v)} {num(ry_v)} 0 0 1 {num(-rx_v)} {num(-ry_v)}v{num(-(h - 2 * ry_v))}"
                f"a{num(rx_v)} {num(ry_v)} 0 0 1 {num(rx_v)} {num(-ry_v)}Z")
    raise SystemExit(f"unsupported SVG element <{tag}>")


def icon_path(name: str) -> str:
    text = (ICON_DIR / f"{name}.svg").read_text()
    root = ET.fromstring(re.sub(r"<!--.*?-->", "", text, flags=re.S))
    if root.attrib.get("viewBox") != "0 0 24 24":
        raise SystemExit(f"{name}.svg: expected a 24x24 Lucide viewBox")
    return "".join(element_path(el) for el in root)


def gen_icon_data() -> str:
    spec = json.loads(ICONS_JSON.read_text())
    paths = {i["name"]: icon_path(i["name"]) for i in spec["icons"]}
    out = [HEADER, "pragma Singleton\nimport QtQuick\n\n",
           f"// {spec['library']} {spec['version']} ({spec['license']}).\n",
           "// Outlines on a 24 x 24 grid, stroked by MeridianIcon.\n",
           "QtObject {\n",
           f"    readonly property string lucideVersion: {js(spec['version'])}\n",
           f"    readonly property var names: {js(list(paths))}\n",
           f"    readonly property var paths: ({js(paths)})\n",
           "}\n"]
    return "".join(out)


# ---------------------------------------------------------------- main

def outputs() -> tuple[dict[Path, str], dict[Path, bytes]]:
    core, brands = core_gen.load()
    text = {
        QML_DIR / "Tokens.qml": gen_tokens(core, brands),
        QML_DIR / "ColorScheme.qml": gen_color_scheme(core),
        QML_DIR / "TypeScale.qml": gen_type_scale(core),
        QML_DIR / "Metrics.qml": gen_metrics(),
        QML_DIR / "IconData.qml": gen_icon_data(),
    }
    binary = {QML_DIR / "fonts" / p.name: p.read_bytes() for p in sorted(FONT_DIR.glob("*.ttf"))}
    binary[QML_DIR / "fonts" / "OFL.txt"] = (FONT_DIR / "OFL.txt").read_bytes()
    return text, binary


def write_or_check(check_only: bool) -> list[str]:
    text, binary = outputs()
    stale = []
    for path, content in text.items():
        if check_only:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    for path, content in binary.items():
        if check_only:
            if not path.exists() or path.read_bytes() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    return stale


def main() -> int:
    check_only = "--check" in sys.argv
    stale = write_or_check(check_only)
    core, brands = core_gen.load()
    failures = core_gen.check_contrast(core, brands)
    for f in failures:
        print("contrast:", f)
    for s in stale:
        print("stale:", s)
    if not failures and not stale:
        print(f"ok: QML tokens for {len(brands)} brands x 2 themes")
    return 1 if failures or stale else 0


if __name__ == "__main__":
    sys.exit(main())

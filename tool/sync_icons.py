#!/usr/bin/env python3
"""Copy the icons listed in tokens/icons.json from lucide-static into assets/icons/
and regenerate lib/src/foundation/meridian_icons.g.dart.

  npm pack lucide-static@1.37.0 && tar xzf lucide-static-1.37.0.tgz
  python3 tool/sync_icons.py path/to/package/icons
"""
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
spec = json.loads((ROOT / "tokens" / "icons.json").read_text())
names = [i["name"] for i in spec["icons"]]

if len(sys.argv) > 1:
    src = Path(sys.argv[1])
    dest = ROOT / "assets" / "icons"
    dest.mkdir(parents=True, exist_ok=True)
    for n in names:
        shutil.copyfile(src / f"{n}.svg", dest / f"{n}.svg")


def camel(name: str) -> str:
    parts = name.split("-")
    out = parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    return out if not out[0].isdigit() else "i" + out


out = [
    "// GENERATED by tool/sync_icons.py from tokens/icons.json. Do not edit.\n",
    "// ignore_for_file: public_member_api_docs\n\n",
    f"/// Icon names in Meridian's Lucide set ({spec['library']} {spec['version']}).\n",
    "/// Pass them to `MeridianIcon` or any component's `icon`.\n",
    "abstract final class MeridianIcons {\n",
]
group = None
for i in spec["icons"]:
    if i["group"] != group:
        group = i["group"]
        out.append(f"\n  // {group}\n")
    out.append(f"  static const {camel(i['name'])} = '{i['name']}';\n")
out.append("\n  /// Every icon name.\n  static const all = <String>[\n")
for n in names:
    out.append(f"    {camel(n)},\n")
out.append("  ];\n}\n")
target = ROOT / "lib" / "src" / "foundation" / "meridian_icons.g.dart"
formatted = subprocess.run(
    ["dart", "format", f"--stdin-name={target.relative_to(ROOT)}"],
    input="".join(out), capture_output=True, text=True, check=True, cwd=ROOT,
).stdout
target.write_text(formatted)
print(f"{len(names)} icons")
